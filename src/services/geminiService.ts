export async function fileToGenerativePart(file: File): Promise<Part> {
  const base64EncodedDataPromise = new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onloadend = () => {
      if (typeof reader.result !== 'string') {
        reject(new Error('Failed to read attachment.'));
        return;
      }
      const separator = reader.result.indexOf(',');
      if (separator === -1) {
        reject(new Error('Failed to read attachment.'));
        return;
      }
      resolve(reader.result.slice(separator + 1));
    };
    reader.onerror = () => reject(new Error('Failed to read attachment.'));
    reader.readAsDataURL(file);
  });
  return {
    inlineData: {
      data: await base64EncodedDataPromise,
      mimeType: file.type,
    },
  };
}

export const generateImage = async (prompt: string): Promise<string> => {
    requireServerSideProvider();
    const response = await createAiClient().models.generateContent({
        model: 'gemini-2.5-flash-image',
        contents: prompt,
    });

    for (const part of response.candidates?.[0]?.content?.parts || []) {
        if (part.inlineData) {
            return `data:${part.inlineData.mimeType};base64,${part.inlineData.data}`;
        }
    }
    throw new Error("No image was generated by the API.");
};

export const startChat = (systemInstruction: string, model: string = 'gemini-3-flash-preview', config: Record<string, unknown> = {}): Chat => {
  requireServerSideProvider();
  const chat = createAiClient().chats.create({
    model: model,
    config: {
      ...config,
      systemInstruction,
    },
  });
  return chat;
};

export const generateOneOffContentStream = async (
    text: string, 
    attachmentFile: File | null,
    systemInstruction: string,
    model: string = 'gemini-3-flash-preview',
    config: Record<string, unknown> = {}
) => {
    requireServerSideProvider();
    const parts: Part[] = [];
    if (attachmentFile) {
        parts.push(await fileToGenerativePart(attachmentFile));
    }
    if (text.trim()) {
        parts.push({text});
    }

    if (parts.length === 0) return null;

    const result = await createAiClient().models.generateContentStream({
        model: model,
        contents: { parts },
        config: {
          ...config,
          systemInstruction: systemInstruction
        }
    });

    return result;
};

export const generateJsonContent = async (prompt: string, schema: Record<string, unknown>, model: string = 'gemini-3-flash-preview') => {
    requireServerSideProvider();
    const response = await createAiClient().models.generateContent({
        model: model,
        contents: prompt,
        config: {
            responseMimeType: "application/json",
            responseSchema: schema,
        },
    });

    try {
        const jsonText = response.text.trim();
        return JSON.parse(jsonText);
    } catch (e) {
        console.error("Failed to parse JSON response:", response.text);
        throw new Error("Invalid JSON response from model.");
    }
};


